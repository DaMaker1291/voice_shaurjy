"""
JARVIS Ambient Acoustic Guardian
=================================
Monitors microphone feeds locally for specific environmental triggers:
- Glass breaking detection
- Baby crying detection
- Doorbell ringing
- Smoke alarm / fire alarm
- Dog barking
- Intrusion / loud noise
- Custom sound patterns

All processing is LOCAL — no audio leaves the device.
"""

